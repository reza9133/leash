// Creates fresh test accounts, writes them to .env and asks Studionet to fund them.
// Usage: node scripts/keys.mjs            (does nothing when .env already holds an OWNER_KEY)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";

const envUrl = new URL("../.env", import.meta.url);
if (existsSync(envUrl) && /^OWNER_KEY=0x[0-9a-fA-F]{64}/m.test(readFileSync(envUrl, "utf8"))) {
  console.log(".env already has an OWNER_KEY, nothing to do. Delete the file to start over.");
  process.exit(0);
}
const sdk = await import("genlayer-js");
const { studionet } = await import("genlayer-js/chains");
const RPC = studionet?.rpcUrls?.default?.http?.[0];

const names = ["OWNER_KEY", "AGENT_KEY", "WATCHER_KEY"];
const keys = Object.fromEntries(names.map((n) => [n, "0x" + randomBytes(32).toString("hex")]));
const lines = [
  "# Generated by scripts/keys.mjs. These accounts are for Studionet tests only; never put real funds on them.",
  ...names.map((n) => `${n}=${keys[n]}`),
  "GUARDIAN_KEY=",
  "OUTSIDER_KEY=",
  "LEASH_ADDRESS=",
  "",
];
writeFileSync(envUrl, lines.join("\n"));
console.log("Wrote .env with three new accounts:");

async function fund(address, wei) {
  // Studio's simulator can credit an account. The number is written by hand because JSON.stringify cannot carry a BigInt.
  const body = `{"jsonrpc":"2.0","id":1,"method":"sim_fundAccount","params":["${address}",${wei}]}`;
  const res = await fetch(RPC, { method: "POST", headers: { "content-type": "application/json" }, body });
  const out = await res.json();
  if (out.error) throw new Error(out.error.message ?? JSON.stringify(out.error));
}
for (const [name, wei] of [["OWNER_KEY", "1000000000000000000"], ["AGENT_KEY", "100000000000000000"], ["WATCHER_KEY", "200000000000000000"]]) {
  const address = sdk.createAccount(keys[name]).address;
  try {
    await fund(address, wei);
    console.log(`  ${name}  ${address}  funded`);
  } catch (err) {
    console.log(`  ${name}  ${address}  NOT funded automatically (${String(err?.message ?? err).slice(0, 80)}). Fund it from the Studio faucet.`);
  }
}
console.log("Load them with:  set -a; . ./.env; set +a   (the run script does this for you)");
